#!/usr/bin/env node
'use strict';

/*
 * Android string resources from locales/*.json, the same translations the
 * desktop uses.
 *
 * Only the keys the app uses are written: every R.string.<key> and
 * @string/<key> in android/app/src. A key that is a Java keyword gets a
 * trailing underscore as a resource name (protected -> R.string.protected_).
 * Placeholders stay as {name}; the app fills them in (Text.kt).
 *
 * Writes res/values/strings.xml (English) and res/values-<lang>/strings.xml
 * for every other language, plus res/xml/locales_config.xml so Android 13+
 * lists the app's languages in its per-app language setting. With nothing
 * set there, the app follows the system language; right-to-left languages
 * are mirrored by the system (android:supportsRtl).
 *
 *   node android/scripts/gen-strings.js           write the files
 *   node android/scripts/gen-strings.js --check   fail if they are out of date
 */

const fs = require('fs');
const path = require('path');

const repo = path.join(__dirname, '..', '..');
const appSrc = path.join(repo, 'android', 'app', 'src');
const res = path.join(appSrc, 'main', 'res');
const check = process.argv.includes('--check');

const JAVA_KEYWORDS = new Set(('abstract assert boolean break byte case catch char class const continue default do double ' +
  'else enum extends final finally float for goto if implements import instanceof int interface long native new package ' +
  'private protected public return short static strictfp super switch synchronized this throw throws transient try void ' +
  'volatile while true false null').split(' '));

// Android's own names for a few languages (the old ISO codes it still uses).
const QUALIFIER = { he: 'iw', id: 'in' };

function resName(key) { return JAVA_KEYWORDS.has(key) ? `${key}_` : key; }

function usedKeys() {
  const keys = new Set();
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) { if (!/^(values.*|build)$/.test(e.name)) walk(full); continue; }
      if (!/\.(kt|java|xml)$/.test(e.name)) continue;
      const src = fs.readFileSync(full, 'utf8');
      for (const m of src.matchAll(/(?<!android\.)\bR\.string\.(\w+)|(?<!android:)@string\/(\w+)/g)) keys.add(m[1] || m[2]);
    }
  })(appSrc);
  keys.delete('app_name');
  // Back from resource names to locale keys.
  return [...keys].map((k) => (k.endsWith('_') && JAVA_KEYWORDS.has(k.slice(0, -1)) ? k.slice(0, -1) : k)).sort();
}

/* Text as an Android string resource: XML-escaped, quotes, apostrophes and
 * backslashes escaped, a leading @ or ? escaped, newlines kept, and % made
 * literal (these strings are never passed to String.format). */
function escape(s) {
  let t = s.replace(/\\/g, '\\\\').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '\\"').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\t/g, '\\t');
  if (/^[@?]/.test(t)) t = `\\${t}`;
  if (/^\s|\s$/.test(t)) t = `"${t}"`;
  return t;
}

function stringsXml(code, keys, strings) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by android/scripts/gen-strings.js from locales/${code}.json. Do not edit. -->`,
    '<resources>'];
  for (const k of keys) {
    if (typeof strings[k] !== 'string') continue;
    const fmt = strings[k].includes('%') ? ' formatted="false"' : '';
    lines.push(`    <string name="${resName(k)}"${fmt}>${escape(strings[k])}</string>`);
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

/* The language list and locale tags the desktop offers (contexts/LanguageContext.js). */
function offered() {
  const src = fs.readFileSync(path.join(repo, 'contexts', 'LanguageContext.js'), 'utf8');
  return [...src.matchAll(/\{ code: '([a-z]{2,3})', name: '([^']*)', locale: '([^']+)' \}/g)].map((m) => ({ code: m[1], name: m[2], locale: m[3] }));
}

function main() {
  const keys = usedKeys();
  const en = JSON.parse(fs.readFileSync(path.join(repo, 'locales', 'en.json'), 'utf8'));
  const missing = keys.filter((k) => typeof en[k] !== 'string');
  if (missing.length) throw new Error(`not in locales/en.json: ${missing.join(', ')}`);

  const langs = offered();
  if (langs.length < 2) throw new Error('could not read the language list from contexts/LanguageContext.js');
  const out = new Map();
  for (const { code } of langs) {
    const strings = JSON.parse(fs.readFileSync(path.join(repo, 'locales', `${code}.json`), 'utf8'));
    const lacking = keys.filter((k) => typeof strings[k] !== 'string');
    if (lacking.length) throw new Error(`locales/${code}.json lacks ${lacking.join(', ')}`);
    const dir = code === 'en' ? 'values' : `values-${QUALIFIER[code] || code}`;
    out.set(path.join(res, dir, 'strings.xml'), stringsXml(code, keys, strings));
  }
  const cfg = ['<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by android/scripts/gen-strings.js. Do not edit. -->',
    '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
    ...langs.map(({ locale }) => `    <locale android:name="${locale}" />`),
    '</locale-config>', ''].join('\n');
  out.set(path.join(res, 'xml', 'locales_config.xml'), cfg);
  // The in-app language choice (Settings → Language): each language's tag
  // and its own name for itself, in the desktop's order.
  const item = (v) => `        <item>${escape(v)}</item>`;
  const names = ['<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by android/scripts/gen-strings.js. Do not edit. -->',
    '<resources>',
    '    <string-array name="language_tags" translatable="false">', ...langs.map(({ locale }) => item(locale)), '    </string-array>',
    '    <string-array name="language_names" translatable="false">', ...langs.map(({ name }) => item(name)), '    </string-array>',
    '</resources>', ''].join('\n');
  out.set(path.join(res, 'values', 'languages.xml'), names);

  // Generated folders of languages no longer offered.
  const stale = fs.readdirSync(res).filter((d) => /^values-[a-z]{2,3}$/.test(d)
    && fs.existsSync(path.join(res, d, 'strings.xml')) && !out.has(path.join(res, d, 'strings.xml')));

  if (check) {
    const wrong = [...out].filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text).map(([f]) => path.relative(repo, f));
    wrong.push(...stale.map((d) => path.relative(repo, path.join(res, d))));
    if (wrong.length) {
      console.error(`[strings] out of date (run node android/scripts/gen-strings.js): ${wrong.join(', ')}`);
      process.exit(1);
    }
    console.log(`[strings] up to date: ${keys.length} keys, ${langs.length} languages`);
    return;
  }
  for (const [f, text] of out) {
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
  }
  for (const d of stale) fs.rmSync(path.join(res, d), { recursive: true, force: true });
  console.log(`[strings] ${keys.length} keys in ${langs.length} languages`);
}

try {
  main();
} catch (e) {
  console.error(`[strings] ${e.message}`);
  process.exit(1);
}
