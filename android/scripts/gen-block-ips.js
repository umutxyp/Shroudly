#!/usr/bin/env node
'use strict';

/*
 * The known block pages and sinkholes (electron/censor-fingerprints.js) for the
 * Android engine's --block-ip arguments, as the desktop passes them: an answer
 * pointing at one is forged, so the engine refuses it and keeps looking.
 * Writes android/app/src/main/assets/block-ips.txt.
 *
 *   node android/scripts/gen-block-ips.js           write it
 *   node android/scripts/gen-block-ips.js --check   fail if it is out of date
 */

const fs = require('fs');
const path = require('path');
const { ALL } = require('../../electron/censor-fingerprints');

const out = path.join(__dirname, '..', 'app', 'src', 'main', 'assets', 'block-ips.txt');
const text = ['# Generated by android/scripts/gen-block-ips.js from electron/censor-fingerprints.js. Do not edit.',
  ...ALL, ''].join('\n');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) {
    console.error('[block-ips] out of date: run node android/scripts/gen-block-ips.js');
    process.exit(1);
  }
  console.log(`[block-ips] up to date (${ALL.length} addresses)`);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`[block-ips] ${ALL.length} addresses`);
}
