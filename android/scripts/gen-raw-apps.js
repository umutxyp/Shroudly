#!/usr/bin/env node
'use strict';

/*
 * The services whose servers Shroudly can name (electron/raw-apps.js), for
 * the Android app: one line per range or name, "<name> <cidr>" or
 * "<name> .<domain>". Names the app behind a connection that is not TLS or
 * HTTP and cannot get through (RawApps.kt), as the desktop does.
 * Writes android/app/src/main/assets/raw-apps.txt, and the same rows for the
 * Apple tunnel (apple/Tunnel/RawAppsList.swift: TorNotice names the app the
 * Tor question is about, as Android and the desktop do). Also "Apps always
 * through Tor" (electron/tor-apps.js) for both: TorAppsList.kt and
 * apple/Shared/TorAppsList.swift.
 *
 *   node android/scripts/gen-raw-apps.js           write it
 *   node android/scripts/gen-raw-apps.js --check   fail if it is out of date
 */

const fs = require('fs');
const path = require('path');
const { SERVICES } = require('../../electron/raw-apps');
const TorApps = require('../../electron/tor-apps');

const out = path.join(__dirname, '..', 'app', 'src', 'main', 'assets', 'raw-apps.txt');
const rows = [];
for (const s of SERVICES) {
  for (const c of s.cidrs) rows.push(`${s.name} ${c}`);
  for (const d of s.domains) rows.push(`${s.name} .${d}`);
}
const text = ['# Generated by android/scripts/gen-raw-apps.js from electron/raw-apps.js. Do not edit.', ...rows, ''].join('\n');

const swiftOut = path.join(__dirname, '..', '..', 'apple', 'Tunnel', 'RawAppsList.swift');
const q = (x) => JSON.stringify(x);
const swift = [
  '// Generated by android/scripts/gen-raw-apps.js from electron/raw-apps.js. Do not edit.',
  '',
  '/* The services whose servers Shroudly can name: (name, "cidr") or (name, ".domain"). */',
  'enum RawAppsList {',
  '    static let rows: [(String, String)] = [',
  ...rows.map((r) => { const i = r.lastIndexOf(' '); return `        (${q(r.slice(0, i))}, ${q(r.slice(i + 1))}),`; }),
  '    ]',
  '}',
  '',
].join('\n');

const torEntries = (a) => [...a.names, ...(a.ranges || [])];
const ktOut = path.join(__dirname, '..', 'app', 'src', 'main', 'java', 'me', 'codeshare', 'shroudly', 'TorAppsList.kt');
const kt = [
  '// Generated by android/scripts/gen-raw-apps.js from electron/tor-apps.js. Do not edit.',
  'package me.codeshare.shroudly',
  '',
  '/* "Apps always through Tor": each app, and the names and ranges the engine sends through Tor for it. */',
  'object TorAppsList {',
  '    data class App(val id: String, val name: String, val entries: List<String>)',
  '',
  '    val apps = listOf(',
  ...TorApps.APPS.map((a) => `        App(${q(a.id)}, ${q(a.name)}, listOf(${torEntries(a).map(q).join(', ')})),`),
  '    )',
  '}',
  '',
].join('\n');
const swiftAppsOut = path.join(__dirname, '..', '..', 'apple', 'Shared', 'TorAppsList.swift');
const swiftApps = [
  '// Generated by android/scripts/gen-raw-apps.js from electron/tor-apps.js. Do not edit.',
  '',
  '/* "Apps always through Tor": each app, and the names and ranges the engine sends through Tor for it. */',
  'enum TorAppsList {',
  '    struct App { let id: String; let name: String; let entries: [String] }',
  '',
  '    static let apps: [App] = [',
  ...TorApps.APPS.map((a) => `        App(id: ${q(a.id)}, name: ${q(a.name)}, entries: [${torEntries(a).map(q).join(', ')}]),`),
  '    ]',
  '}',
  '',
].join('\n');

const files = [[out, text], [swiftOut, swift], [ktOut, kt], [swiftAppsOut, swiftApps]];
if (process.argv.includes('--check')) {
  for (const [f, body] of files) {
    if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== body) {
      console.error(`[raw-apps] ${path.basename(f)} out of date: run node android/scripts/gen-raw-apps.js`);
      process.exit(1);
    }
  }
  console.log(`[raw-apps] up to date (${rows.length} entries)`);
} else {
  for (const [f, body] of files) { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, body); }
  console.log(`[raw-apps] ${rows.length} entries`);
}
