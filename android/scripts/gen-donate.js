#!/usr/bin/env node
'use strict';

/*
 * The ways to support Shroudly (components/donate.json, the desktop's), for
 * the Android app (Support.kt), one per line:
 *   paypal <url> | recipient <name> | nopay <countries...>
 *   account <id> <currency> <countries...>, then its "field <key> <value>"
 *   lines and "bank <name and address>"
 * Writes android/app/src/main/assets/donate.txt.
 *
 *   node android/scripts/gen-donate.js           write it
 *   node android/scripts/gen-donate.js --check   fail if it is out of date
 */

const fs = require('fs');
const path = require('path');
const data = require('../../components/donate.json');

const out = path.join(__dirname, '..', 'app', 'src', 'main', 'assets', 'donate.txt');
const one = (s) => String(s).replace(/\s*\n\s*/g, ' ');
const rows = [`paypal ${data.paypal}`, `recipient ${one(data.recipient)}`, `nopay ${data.noPay.join(' ')}`];
for (const a of data.accounts) {
  rows.push(['account', a.id, a.currency, ...a.countries].join(' '));
  for (const [k, v] of a.fields) rows.push(`field ${k} ${one(v)}`);
  rows.push(`bank ${one(a.bank)}`);
}
const text = ['# Generated by android/scripts/gen-donate.js from components/donate.json. Do not edit.', ...rows, ''].join('\n');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) {
    console.error('[donate] out of date: run node android/scripts/gen-donate.js');
    process.exit(1);
  }
  console.log(`[donate] up to date (${data.accounts.length} accounts)`);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`[donate] ${data.accounts.length} accounts`);
}
