#!/usr/bin/env node
'use strict';

/*
 * The Apple app's strings from locales/*.json, the same translations the
 * desktop and Android use.
 *
 * Only the keys the app uses are written: every tr("key") and
 * labelKey: "key" in apple/App, apple/Shared and apple/Tunnel. Placeholders
 * stay as {name}; the app fills them in (Shared/Strings.swift).
 *
 * Writes apple/Localization/<language>.lproj/Localizable.strings for every
 * language the desktop offers (contexts/LanguageContext.js), and
 * InfoPlist.strings with the system's prompts (INFO_PLIST below). Apple's
 * folder names differ from the desktop's codes for two (LPROJ). The app
 * follows the system's language, or the one chosen for Shroudly alone in the
 * system's settings; right-to-left languages are mirrored by SwiftUI.
 *
 *   node apple/scripts/gen-strings.js           write the files
 *   node apple/scripts/gen-strings.js --check   fail if they are out of date
 *
 * --check also fails when the Xcode project does not list every language
 * (knownRegions in Shroudly.xcodeproj/project.pbxproj).
 */

const fs = require('fs');
const path = require('path');

const repo = path.join(__dirname, '..', '..');
const apple = path.join(repo, 'apple');
const outDir = path.join(apple, 'Localization');
const check = process.argv.includes('--check');

// Apple's names: Simplified Chinese, and the desktop's Brazilian Portuguese.
const LPROJ = { zh: 'zh-Hans', pt: 'pt-BR' };
// Info.plist keys the system shows, and the locale keys that hold them.
const INFO_PLIST = { NSLocalNetworkUsageDescription: 'appleLocalNetworkUsage' };

function lproj(code) { return LPROJ[code] || code; }

function usedKeys() {
  const keys = new Set(Object.values(INFO_PLIST));
  for (const dir of ['App', 'Shared', 'Tunnel']) {
    (function walk(d) {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const full = path.join(d, e.name);
        if (e.isDirectory()) { walk(full); continue; }
        if (!e.name.endsWith('.swift')) continue;
        const src = fs.readFileSync(full, 'utf8');
        // tr("key"), labelKey: "key", and the App Intents' titles (Intents.swift).
        for (const m of src.matchAll(/\btr\(\s*"(\w+)"|\blabelKey:\s*"(\w+)"|LocalizedStringResource\s*=\s*"(\w+)"|\bshortTitle:\s*"(\w+)"/g)) keys.add(m[1] || m[2] || m[3] || m[4]);
      }
    })(path.join(apple, dir));
  }
  return [...keys].sort();
}

/* Text as a .strings value: backslashes, quotes and control characters escaped. */
function escape(s) {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t').replace(/\r/g, '\\r');
}

function stringsFile(code, pairs) {
  const lines = [`/* Generated by apple/scripts/gen-strings.js from locales/${code}.json. Do not edit. */`, ''];
  for (const [k, v] of pairs) lines.push(`"${k}" = "${escape(v)}";`);
  lines.push('');
  return lines.join('\n');
}

/* The languages the desktop offers (contexts/LanguageContext.js). */
function offered() {
  const src = fs.readFileSync(path.join(repo, 'contexts', 'LanguageContext.js'), 'utf8');
  return [...src.matchAll(/\{ code: '([a-z]{2,3})', name: '([^']*)', locale: '([^']+)' \}/g)].map((m) => m[1]);
}

function main() {
  const keys = usedKeys();
  const en = JSON.parse(fs.readFileSync(path.join(repo, 'locales', 'en.json'), 'utf8'));
  const missing = keys.filter((k) => typeof en[k] !== 'string');
  if (missing.length) throw new Error(`not in locales/en.json: ${missing.join(', ')}`);

  const langs = offered();
  if (langs.length < 2) throw new Error('could not read the language list from contexts/LanguageContext.js');
  const out = new Map();
  for (const code of langs) {
    const strings = JSON.parse(fs.readFileSync(path.join(repo, 'locales', `${code}.json`), 'utf8'));
    const lacking = keys.filter((k) => typeof strings[k] !== 'string');
    if (lacking.length) throw new Error(`locales/${code}.json lacks ${lacking.join(', ')}`);
    const dir = path.join(outDir, `${lproj(code)}.lproj`);
    out.set(path.join(dir, 'Localizable.strings'), stringsFile(code, keys.map((k) => [k, strings[k]])));
    out.set(path.join(dir, 'InfoPlist.strings'), stringsFile(code, Object.entries(INFO_PLIST).map(([p, k]) => [p, strings[k]])));
  }

  // Generated folders of languages no longer offered.
  const wanted = new Set(langs.map((c) => `${lproj(c)}.lproj`));
  const stale = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((d) => d.endsWith('.lproj') && !wanted.has(d)) : [];

  if (check) {
    const wrong = [...out].filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text).map(([f]) => path.relative(repo, f));
    wrong.push(...stale.map((d) => path.relative(repo, path.join(outDir, d))));
    const pbx = fs.readFileSync(path.join(apple, 'Shroudly.xcodeproj', 'project.pbxproj'), 'utf8');
    const regions = (pbx.match(/knownRegions = \(([^)]*)\)/) || [, ''])[1].split(',').map((s) => s.trim().replace(/"/g, '')).filter(Boolean);
    const unlisted = langs.map(lproj).filter((l) => !regions.includes(l));
    if (unlisted.length) wrong.push(`knownRegions in Shroudly.xcodeproj lacks ${unlisted.join(', ')}`);
    if (wrong.length) {
      console.error(`[strings] out of date (run node apple/scripts/gen-strings.js): ${wrong.join(', ')}`);
      process.exit(1);
    }
    console.log(`[strings] up to date: ${keys.length} keys, ${langs.length} languages`);
    return;
  }
  for (const [f, text] of out) {
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
  }
  for (const d of stale) fs.rmSync(path.join(outDir, d), { recursive: true, force: true });
  console.log(`[strings] ${keys.length} keys in ${langs.length} languages`);
}

try {
  main();
} catch (e) {
  console.error(`[strings] ${e.message}`);
  process.exit(1);
}
