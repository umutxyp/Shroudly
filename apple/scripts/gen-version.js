#!/usr/bin/env node
'use strict';

/*
 * The Apple app's version from the repository's package.json, as the Android
 * build takes it: apple/Config/Version.xcconfig (not committed) with
 * MARKETING_VERSION (2.6.44) and CURRENT_PROJECT_VERSION, the build number,
 * major*10000 + minor*100 + patch (20644), the same number as Android's
 * versionCode. Run it before every build that leaves this machine
 * (scripts/test.sh and CI do).
 *
 *   node apple/scripts/gen-version.js
 *
 * App Store Connect takes one upload per build number: to upload the same
 * version again, add a fourth part on the command line, e.g.
 * xcodebuild ... CURRENT_PROJECT_VERSION=20644.1
 */

const fs = require('fs');
const path = require('path');

const repo = path.join(__dirname, '..', '..');
const { version } = JSON.parse(fs.readFileSync(path.join(repo, 'package.json'), 'utf8'));
const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(version || '');
if (!m) {
  console.error(`[version] package.json's version "${version}" is not major.minor.patch`);
  process.exit(1);
}
const [major, minor, patch] = m.slice(1).map(Number);
if (minor > 99 || patch > 99) {
  console.error(`[version] ${version}: minor and patch must be below 100 for the build number`);
  process.exit(1);
}
const build = major * 10000 + minor * 100 + patch;
const text = [
  '// Generated by apple/scripts/gen-version.js from package.json. Do not edit.',
  `MARKETING_VERSION = ${version}`,
  `CURRENT_PROJECT_VERSION = ${build}`,
  '',
].join('\n');
fs.writeFileSync(path.join(repo, 'apple', 'Config', 'Version.xcconfig'), text);
console.log(`[version] ${version} (${build})`);
